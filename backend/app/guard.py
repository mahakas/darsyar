"""مرزبندی دادهٔ بیرونی برای prompt؛ این helper به‌تنهایی محافظت کامل نیست."""


def wrap_untrusted_data(content: str) -> str:
    """محتوای غیرقابل‌اعتماد را جدا از دستور سیستم علامت‌گذاری می‌کند."""
    safe = content.replace("<<<دادهٔ بیرونی", "‹‹‹دادهٔ بیرونی").replace(">>>دادهٔ بیرونی", "›››دادهٔ بیرونی")
    return f">>>دادهٔ بیرونی\n{safe}\n<<<دادهٔ بیرونی"
